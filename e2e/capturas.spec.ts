import { test } from '@playwright/test'
import { readFileSync } from 'node:fs'
const clave = readFileSync('e2e/.clave-prueba', 'utf8').trim()
const dir = process.env.CAPTURAS ?? 'test-results/capturas'
test.skip(!process.env.CAPTURAS, 'solo bajo demanda')
test('capturas', async ({ browser }) => {
  const m = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage()
  await m.goto('http://127.0.0.1:5173/ingresar')
  await m.waitForTimeout(500)
  await m.screenshot({ path: `${dir}/01.png` })
  await m.goto('http://127.0.0.1:5173/crear-cuenta')
  await m.waitForTimeout(300)
  await m.screenshot({ path: `${dir}/02.png` })
  const d = await (await browser.newContext({ viewport: { width: 1280, height: 844 } })).newPage()
  await d.goto('http://127.0.0.1:5173/ingresar')
  await d.getByLabel('Correo').fill('admin@prueba.test')
  await d.getByLabel('Contraseña').fill(clave)
  await d.getByRole('button', { name: 'Ingresar' }).click()
  await d.waitForURL(/panel/)
  await d.waitForTimeout(800)
  await d.screenshot({ path: `${dir}/10.png` })
  await d.getByText(/^AA-/).first().click()
  await d.getByRole('button', { name: 'Guardar estado' }).waitFor()
  await d.waitForTimeout(800)
  await d.screenshot({ path: `${dir}/11.png`, fullPage: true })
  await d.goto('http://127.0.0.1:5173/panel/personal')
  await d.waitForTimeout(800)
  await d.screenshot({ path: `${dir}/14.png` })
  const a = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage()
  await a.goto('http://127.0.0.1:5173/ingresar')
  await a.getByLabel('Correo').fill('fontanero@prueba.test')
  await a.getByLabel('Contraseña').fill(clave)
  await a.getByRole('button', { name: 'Ingresar' }).click()
  await a.waitForURL(/asignados/)
  await a.waitForTimeout(600)
  await a.screenshot({ path: `${dir}/08.png` })
  await a.getByText(/^AA-/).first().click()
  await a.getByRole('button', { name: 'Guardar estado' }).waitFor()
  await a.waitForTimeout(800)
  await a.screenshot({ path: `${dir}/09.png`, fullPage: true })
  await d.goto('http://127.0.0.1:5173/panel')
  await d.setViewportSize({ width: 390, height: 844 })
  await d.waitForTimeout(600)
  await d.screenshot({ path: `${dir}/10m.png` })
})
